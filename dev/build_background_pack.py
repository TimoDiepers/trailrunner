"""Build ``examples/background_pack.parquet`` from real EcoSpold 1 files.

Source corpus: ``dev/BAFU ecospold/raw/ecoSpold files/`` -- ~12,000 EcoSpold 1
process files (``process_<uuid>.xml``), generated by openLCA. The root
element is ``<ecoSpold>`` with **no XML namespace**, so plain
``xml.etree.ElementTree`` tag names work directly:

    ecoSpold/dataset/metaInformation/processInformation/referenceFunction
    ecoSpold/dataset/flowData/exchange (repeated)

``referenceFunction`` carries the dataset's identity (``name``, ``unit``,
``amount`` -- always ``1`` in every file this script touches, i.e. every
``exchange`` below is already expressed per unit of the reference product).
Each ``exchange`` carries ``name``, ``category``, ``subCategory``, ``unit``
and ``meanValue``, plus exactly one of a nested ``<inputGroup>`` or
``<outputGroup>`` element.

**The elementary-vs-technosphere rule, found by inspecting the data rather
than assumed** (confirmed across the *entire* corpus -- every one of
11,947 files, no exceptions, via a full-corpus regex scan of every
``<inputGroup>``/``<outputGroup>`` value):

    outputGroup "0"   the dataset's reference product (exactly one per file)
    outputGroup "4"   an elementary flow emitted to the environment
                      (category one of "emissions to air/water/soil",
                      "non material emissions", "economic issues")
    inputGroup  "4"   an elementary flow drawn from the environment
                      (category "resources", always)
    inputGroup  "5"   a technosphere input -- materials, fuels, electricity,
                      services, infrastructure, waste treatment: this
                      process's own upstream, and exactly what a
                      "unit_process" background row does *not* resolve.

No other group codes occur anywhere in this corpus. Worked example
(``process_0004e814-c18d-42e2-a3f7-ce1fa51a3c2c.xml``, a nuclear-waste
repository dataset):

    <exchange name="Radioactive waste, ..." ...><outputGroup>0</outputGroup>   -> reference product
    <exchange name="Electricity, medium voltage, at grid" ...><inputGroup>5</inputGroup>   -> technosphere (dropped)
    <exchange name="Volume occupied, ..." category="resources" ...><inputGroup>4</inputGroup>   -> elementary (resource)
    <exchange name="Heat, waste" category="emissions to air" ...><outputGroup>4</outputGroup>   -> elementary (emission)

Every row this script writes carries ``basis="unit_process"``: these are
ecoinvent-style unit process datasets (a technology step with its own named
technosphere inputs), not Brightway ``lca.inventory`` results, so their
technosphere inputs are always dropped, never resolved. A dataset whose own
direct exchanges include none of the three flows below is not padded with an
empty row -- it is printed as skipped and left out. A demand for it still
gets no answer from this pack, which is what an honest cutoff is for.

**The flow mapping.** Only three elementary flows are mapped, because they
are the only ones this script's author is confident about (exact EcoSpold
name, unit and substance identity all checked against the corpus directly),
and a wrong IRI characterises as nothing, silently, which is worse than
leaving the flow out:

    "Carbon dioxide, fossil"  -> https://vocab.sentier.dev/flows/co2-fossil  (kg)
    "Methane, fossil"         -> https://vocab.sentier.dev/flows/ch4-fossil  (kg)
    "Dinitrogen monoxide"     -> https://vocab.sentier.dev/flows/n2o         (kg)

These three IRIs are the ones used everywhere in trailrunner
(``trailrunner/models/electricity.py``, ``trailrunner/assessment/dynamic.py``,
``trailrunner/models/natural_gas_pipeline_transport.py``). The pipeline model
once spelled two of them differently (``carbon-dioxide-fossil``,
``methane-fossil``); both have since been reconciled to the spelling below,
which is the one the characterization tables actually read.

Every other elementary flow this script finds (NOx, SO2, particulates,
NMVOC, noise, embodied water, ...) has no IRI mapping attempted here, and is
printed, deduplicated, when the script runs.

**The distribution/mixing/aggregation rule.** A dataset with none of the
three mapped flows is an easy call to leave out (see ``EXCLUDED`` above).
Harder: a dataset that *does* carry a mapped flow, but at a near-zero
amount, because its own direct exchanges are mostly a technosphere input of
the very commodity it produces -- e.g. "Electricity, high voltage, at grid"
(1 kWh out) whose only sizeable input is 1.028 kWh of "Electricity mix" (the
actual generation, one hop upstream and unresolved by this tier), leaving
only a trace of N2O as its own direct emission. Borrowing that row answers
an electricity demand with a plausible-looking near-zero for climate
impact -- worse than a cutoff, because a cutoff is visible.

``_distribution_step_reason`` catches this shape without naming
"electricity" anywhere: a unit process whose *largest* technosphere input is
(a) the same unit as its own reference product, (b) the same commodity --
judged by the leading word of both names before the first comma, e.g.
"Electricity" in both "Electricity mix" and "Electricity, high voltage, at
grid" -- and (c) within a small factor (0.5x-2x) of the reference amount, is
redistributing or blending that same commodity rather than making it.

**The rule is hand-audited against this pack, not fully structural.** Its
"largest" is a unit-blind ``max()`` over amounts in kg, MJ, kWh, m3 and tkm
alike, which is not a comparison that means anything on its own -- the
comparison only becomes meaningful at step (a), where an input of a
different unit is discarded. What follows is the audit, re-run against the
parsed files rather than remembered; every dominant input named here is the
one this script's own ``max()`` picks.

Only the two electricity rows (CH, RER) match all three conditions: their
dominant input is "Electricity mix", 1.028x and 1.035x their own 1 kWh, same
unit, same leading word. Every other kept dataset fails at least one:

- a different unit from the reference product: natural gas at consumer (m3
  of gas into an MJ reference), copper at refinery (4.53 MJ of heavy fuel
  oil), transport, freight, rail (kWh into tkm), transport, natural gas,
  pipeline (MJ into tkm), pig iron (1.51 MJ of blast furnace gas), steel,
  electric (0.751 MJ of natural gas), and aluminium, primary, liquid (14.9
  kWh of electricity);
- the same unit but a different leading word: clinker (1.25 kg of crushed
  limestone), hard coal at mine (1.68 kg of mine spoil disposal), steel,
  converter (0.9 kg of pig iron) -- real upstream materials, not the same
  commodity restated.

**Aluminium is the dataset this rule does not decide honestly.** It survives
only because the unit-blind ``max()`` lands on its 14.9 kWh of electricity,
which is then discarded for having the wrong unit. Look inside the reference
unit and it does contain a same-unit, same-leading-word, in-band input:
"Aluminium oxide, at plant", 1.92 kg per 1 kg of liquid aluminium. Do **not**
"harden" the rule to compare within the reference unit on the strength of
that: alumina into aluminium is the Hall-Heroult reduction, a genuine
producing step, and a rule that rejected it would throw away the one dataset
in this pack where electrolysis CO2 is actually recorded. The leading-word
heuristic simply cannot tell "aluminium oxide -> aluminium" (a reduction)
from "electricity mix -> electricity" (a redistribution); the pack's author
can, and did, one dataset at a time. Treat this function as a cheap guard
that caught the case it was written for, and audit any dataset added to
``DATASETS`` by hand.

Run:

    uv run python dev/build_background_pack.py

Writes ``examples/background_pack.parquet`` and prints what it kept and what
it skipped.
"""

