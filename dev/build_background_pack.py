def parse_dataset(path: Path) -> tuple[dict[str, str], list[tuple[str, str, str, str, float]]]:
    """Read one EcoSpold file: (reference-product identity, exchanges).

    Each exchange is ``(name, category, unit, group, meanValue)`` where
    ``group`` is ``"reference"`` (outputGroup 0), ``"elementary"``
    (outputGroup 4 or inputGroup 4) or ``"technosphere"`` (inputGroup 5) --
    the rule from the module docstring, applied here and nowhere else.
    """
    root = ET.parse(path).getroot()
    dataset = root.find("dataset")
    reference_function = dataset.find("metaInformation/processInformation/referenceFunction")
    geography = dataset.find("metaInformation/processInformation/geography")
    identity = {
        "name": reference_function.get("name"),
        "unit": reference_function.get("unit"),
        "amount": reference_function.get("amount"),
        "location": geography.get("location") if geography is not None else None,
    }

    exchanges: list[tuple[str, str, str, str, float]] = []
    for exchange in dataset.find("flowData").findall("exchange"):
        output_group = exchange.find("outputGroup")
        input_group = exchange.find("inputGroup")
        if output_group is not None and output_group.text == "0":
            group = "reference"
        elif (output_group is not None and output_group.text == "4") or (
            input_group is not None and input_group.text == "4"
        ):
            group = "elementary"
        elif input_group is not None and input_group.text == "5":
            group = "technosphere"
        else:
            raise ValueError(
                f"{path.name}: exchange {exchange.get('name')!r} has an "
                f"unrecognised inputGroup/outputGroup "
                f"({input_group.text if input_group is not None else None!r}/"
                f"{output_group.text if output_group is not None else None!r}); "
                "the rule this script relies on does not cover it"
            )
        exchanges.append(
            (
                exchange.get("name"),
                exchange.get("category"),
                exchange.get("unit"),
                group,
                float(exchange.get("meanValue")),
            )
        )
    return identity, exchanges


def _distribution_step_reason(
    identity: dict[str, str], exchanges: list[tuple[str, str, str, str, float]]
) -> str | None:
    """Structural check: is this dataset redistributing/blending its own
    reference product rather than producing it?

    A unit process whose *largest* technosphere input is the same commodity
    as its own reference product -- same unit, and within a small factor of
    the reference amount -- is a distribution, mixing or aggregation step,
    not a producing one: whatever it emits directly describes that step, not
    the product.

    "Same commodity" is judged the only way available from names alone: the
    leading word of both names, before the first comma, matches
    (``"Electricity"`` in both ``"Electricity mix"`` and ``"Electricity,
    high voltage, at grid"``). Deliberately narrow -- it does not fire on a
    same-unit input that is a genuinely different commodity (1.25 kg of
    crushed limestone into clinker, 0.9 kg of pig iron into converter
    steel).

    ``max()`` here is unit-blind, and stays that way: see the module
    docstring's "distribution/mixing/aggregation rule", which records the
    full audit against ``DATASETS``, and in particular why comparing within
    the reference unit would start rejecting alumina -> aluminium, a real
    producing step. This is a cheap guard that caught the case it was
    written for, not a structural test that can be trusted on a dataset
    nobody has audited.
    """
    technosphere = [
        (name, unit, amount) for name, _cat, unit, group, amount in exchanges if group == "technosphere"
    ]
    if not technosphere:
        return None
    dominant_name, dominant_unit, dominant_amount = max(technosphere, key=lambda t: t[2])

    ref_name = identity["name"]
    ref_unit = identity["unit"]
    ref_amount = float(identity["amount"])
    if dominant_unit != ref_unit:
        return None

    ref_word = ref_name.split(",", 1)[0].strip().split()[0].lower()
    dominant_word = dominant_name.split(",", 1)[0].strip().split()[0].lower()
    if ref_word != dominant_word:
        return None

    if ref_amount == 0:
        return None
    ratio = dominant_amount / ref_amount
    if not (0.5 <= ratio <= 2.0):
        return None

    return (
        f"largest technosphere input is {dominant_name!r} "
        f"({dominant_amount:g} {dominant_unit} per {ref_amount:g} {ref_unit} "
        f"of {ref_name!r}, ratio {ratio:.3g}) -- same commodity, same unit, "
        "within a small factor: a distribution/mixing/aggregation step, not "
        "a producing one"
    )


def build_rows() -> tuple[list[dict[str, Any]], set[str], list[dict[str, str]]]:
    rows: list[dict[str, Any]] = []
    skipped_flows: dict[str, int] = {}
    structural_skips: list[dict[str, str]] = []

    for entry in DATASETS:
        path = CORPUS / entry["file"]
        source = entry["file"].removeprefix("process_").removesuffix(".xml")
        identity, exchanges = parse_dataset(path)

        assert identity["name"] == entry["expected_name"], (
            f"{entry['file']}: expected referenceFunction name "
            f"{entry['expected_name']!r}, found {identity['name']!r}"
        )
        assert identity["location"] == entry["expected_location"], (
            f"{entry['file']}: expected location {entry['expected_location']!r}, "
            f"found {identity['location']!r}"
        )
        assert float(identity["amount"]) == 1.0, (
            f"{entry['file']}: referenceFunction amount is "
            f"{identity['amount']!r}, not 1 -- every meanValue below would "
            "need rescaling by it, and this script does not do that"
        )

        distribution_reason = _distribution_step_reason(identity, exchanges)
        if distribution_reason is not None:
            structural_skips.append(
                {
                    "name": f"{identity['name']} ({identity['location']})",
                    "reason": distribution_reason,
                }
            )
            print(f"skipped dataset: {identity['name']} ({identity['location']}) -- {distribution_reason}")
            continue

        found_any = False
        for name, _category, _unit, group, mean_value in exchanges:
            if group != "elementary":
                continue
            mapping = ELEMENTARY_FLOW_MAP.get(name)
            if mapping is None:
                skipped_flows[name] = skipped_flows.get(name, 0) + 1
                continue
            flow_iri, expected_unit = mapping
            rows.append(
                {
                    "product_iri": entry["product_iri"],
                    "product_unit": identity["unit"],
                    "location": identity["location"],
                    "dataset": identity["name"],
                    "source": source,
                    "basis": "unit_process",
                    "flow_iri": flow_iri,
                    "flow_unit": expected_unit,
                    "amount": mean_value,
                }
            )
            found_any = True

        assert found_any, (
            f"{entry['file']} ({identity['name']!r}) produced no rows -- it "
            "belongs in EXCLUDED, not DATASETS, if it has none of the mapped "
            "flows"
        )
        print(
            f"kept   {identity['name']} ({identity['location']}): "
            f"{sum(1 for r in rows if r['source'] == source)} row(s), source={source}"
        )

    return rows, skipped_flows, structural_skips


def print_excluded() -> None:
    for entry in EXCLUDED:
        print(f"skipped dataset: {entry['name']} -- {entry['reason']}")


def print_skipped_flows(skipped_flows: dict[str, int]) -> None:
    for name in sorted(skipped_flows):
        print(f"skipped flow (no confident IRI mapping): {name!r} (seen {skipped_flows[name]}x)")


def write_pack(rows: list[dict[str, Any]], path: Path) -> None:
    schema = pa.schema(
        [
            ("product_iri", pa.string()),
            ("product_unit", pa.string()),
            ("location", pa.string()),
            ("dataset", pa.string()),
            ("source", pa.string()),
            ("basis", pa.string()),
            ("flow_iri", pa.string()),
            ("flow_unit", pa.string()),
            ("amount", pa.float64()),
        ]
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(pa.Table.from_pylist(rows, schema=schema), path)


if __name__ == "__main__":
    rows, skipped_flows, structural_skips = build_rows()
    print()
    print_excluded()
    print()
    print_skipped_flows(skipped_flows)
    print()
    write_pack(rows, OUT_PATH)
    datasets = {(row["dataset"], row["location"]) for row in rows}
    print(f"wrote {OUT_PATH} ({len(rows)} rows, {len(datasets)} datasets)")
